pluginManagement {
    repositories {
        // GitHub Actions runners sit outside mainland China and cannot resolve
        // plugin markers through the mirrors (KSP failed there). On CI use the
        // official repositories only; local builds keep the faster mirrors.
        if (System.getenv("CI") != "true" && System.getenv("GITHUB_ACTIONS") != "true") {
            maven("https://maven.aliyun.com/repository/google")
            maven("https://maven.aliyun.com/repository/central")
            maven("https://maven.aliyun.com/repository/gradle-plugin")
        }
        google()
        mavenCentral()
        gradlePluginPortal()
    }
}

